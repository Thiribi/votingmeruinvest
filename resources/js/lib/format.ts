/** Compact vote-count formatting — 950 stays "950", 12,400 becomes "12.4K", 3,000,000 becomes "3M". */
export function formatVotes(n: number): string {
  if (n >= 1_000_000) {
    const m = n / 1_000_000;
    return `${m % 1 === 0 ? m : m.toFixed(1)}M`;
  }
  if (n >= 1_000) {
    const k = n / 1_000;
    return `${k % 1 === 0 ? k : k.toFixed(1)}K`;
  }
  return String(n);
}
